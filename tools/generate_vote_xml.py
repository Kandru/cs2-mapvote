#!/usr/bin/env python3
"""Generate workshop/content/.../vote.xml from a fixed pool size (SlotCount=50)."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "workshop" / "content" / "panorama" / "layout" / "custom_game" / "mapvote" / "vote.xml"

SLOT_COUNT = 50
COLS = 10
ROW_COUNT = (SLOT_COUNT + COLS - 1) // COLS  # 5


def tile(pool: str, index: int, vote_var: str, name_var: str, indent: str) -> str:
    if pool == "voted":
        tile_id = f"mv-voted-{index}"
        shot_id = f"mv-voted-shot-{index}"
        votes_id = f"mv-voted-votes-{index}"
    else:
        tile_id = f"mv-{index}"
        shot_id = f"mv-shot-{index}"
        votes_id = f"mv-votes-{index}"
    return "\n".join(
        [
            f'{indent}<Button id="{tile_id}" class="MapTile is-off">',
            f'{indent}\t<Panel id="{shot_id}" class="MapShot mv-map-default" hittest="false" />',
            f'{indent}\t<Panel class="MapFade" hittest="false" />',
            f'{indent}\t<Label class="MapName stratum-medium-condensed" text="{{s:{name_var}}}" hittest="false" />',
            f'{indent}\t<Label id="{votes_id}" class="MapVotes stratum-bold" text="{{s:{vote_var}}}" hittest="false" />',
            f'{indent}\t<Panel class="MapWinnerCheck" hittest="false" />',
            f"{indent}</Button>",
        ]
    )


def build() -> str:
    lines: list[str] = [
        "<!-- AUTO-GENERATED by tools/generate_vote_xml.py — do not edit by hand.",
        "     MapVote fullscreen CS2 vote. Root Panel has no id. Card starts is-off.",
        f"     Voted strip (row 1) + catalog rows of {COLS}. SlotCount={SLOT_COUNT}. -->",
        "<root>",
        "\t<styles>",
        '\t\t<include src="s2r://panorama/styles/csgostyles.vcss" />',
        '\t\t<include src="s2r://panorama/styles/custom_game/mapvote/hud.vcss" />',
        "\t</styles>",
        "",
        '\t<Panel class="HudScreen" hittest="false">',
        '\t\t<Panel id="Vote" class="VoteRoot is-off" hittest="false">',
        '\t\t\t<Panel class="mv-glass" hittest="false" />',
        '\t\t\t<Panel class="mv-scrim-top" hittest="false" />',
        '\t\t\t<Panel class="mv-scrim-bottom" hittest="false" />',
        '\t\t\t<Panel class="VoteColumn" hittest="false">',
        '\t\t\t\t<Panel class="VoteTopBar" hittest="false">',
        '\t\t\t\t\t<Label class="VoteTitle stratum-regular-condensed" text="{s:mv_title}" hittest="false" />',
        '\t\t\t\t\t<Button id="mv-minimize" class="MinimizeBtn">',
        '\t\t\t\t\t\t<Label class="MinimizeLabel stratum-bold-condensed" text="MAP VOTE" hittest="false" />',
        "\t\t\t\t\t</Button>",
        "\t\t\t\t</Panel>",
        '\t\t\t\t<Panel class="VoteBody" hittest="false">',
        '\t\t\t\t\t<Panel id="mv-voted-section" class="VotedSection" hittest="false">',
        '\t\t\t\t\t\t<Panel id="mv-voted-row" class="VotedRow" hittest="false">',
        '\t\t\t\t\t\t\t<Label id="mv-voted-hint" class="VotedHint stratum-regular-condensed" text="{s:mv_hint}" hittest="false" />',
        '\t\t\t\t\t\t\t<Panel id="mv-voted-strip" class="VotedStrip vw-0" hittest="false">',
    ]

    for i in range(SLOT_COUNT):
        lines.append(tile("voted", i, f"vv{i}", f"vn{i}", "\t\t\t\t\t\t\t\t"))

    lines.extend(
        [
            "\t\t\t\t\t\t\t</Panel>",
            "\t\t\t\t\t\t</Panel>",
            "\t\t\t\t\t</Panel>",
            '\t\t\t\t\t<Panel class="MapGridHost" hittest="false">',
            '\t\t\t\t\t\t<Panel id="mv-grid" class="MapGrid" hittest="false">',
            '\t\t\t\t\t\t\t<Panel id="mv-catalog" class="MapCatalog rows-0" hittest="false">',
        ]
    )

    for row in range(ROW_COUNT):
        # Default: all catalog rows start is-off; painter enables rows that have maps.
        lines.append(
            f'\t\t\t\t\t\t\t\t<Panel id="mv-crow-{row}" class="CatalogRow is-off" hittest="false">'
        )
        start = row * COLS
        end = min(start + COLS, SLOT_COUNT)
        for i in range(start, end):
            lines.append(tile("grid", i, f"v{i}", f"n{i}", "\t\t\t\t\t\t\t\t\t"))
        lines.append("\t\t\t\t\t\t\t\t</Panel>")

    lines.extend(
        [
            "\t\t\t\t\t\t\t</Panel>",
            "\t\t\t\t\t\t</Panel>",
            '\t\t\t\t\t\t<Panel class="MapGridFadeTop" hittest="false" />',
            '\t\t\t\t\t\t<Panel class="MapGridFadeBottom" hittest="false" />',
            "\t\t\t\t\t</Panel>",
            "\t\t\t\t</Panel>",
            "\t\t\t</Panel>",
            "\t\t</Panel>",
            "\t</Panel>",
            "</root>",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if committed vote.xml differs from generated output",
    )
    args = parser.parse_args()
    text = build().replace("\r\n", "\n")
    if args.check:
        if not OUT.is_file():
            print(f"missing {OUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        existing = OUT.read_text(encoding="utf-8").replace("\r\n", "\n")
        if existing != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run tools/generate_vote_xml.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
