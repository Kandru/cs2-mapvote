#!/usr/bin/env python3
"""Generate workshop/content/.../vote_vN.xml from fixed pool sizes."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from mapvote_layout import (
    CATALOG_ROW_HEIGHT_PX,
    COLS,
    FILTER_SORT_SLOTS,
    FILTER_TYPE_SLOTS,
    HUD_VCSS_NAME,
    PANORAMA_VERSION,
    ROW_COUNT,
    SLOT_COUNT,
    VOTED_SLOT_PITCH_PX,
    VOTE_XML_NAME,
)

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "workshop" / "content" / "panorama" / "layout" / "custom_game" / "mapvote" / VOTE_XML_NAME
HUD_VCSS = ROOT / "workshop" / "content" / "panorama" / "styles" / "custom_game" / "mapvote" / HUD_VCSS_NAME
CREDIT = "made by kandru.net - visit github.com/kandru/cs2-mapvote"
LAYOUT_TAG = (
    f"{PANORAMA_VERSION} slots={SLOT_COUNT} cols={COLS} rows={ROW_COUNT} "
    f"filter_types={FILTER_TYPE_SLOTS} filter_sorts={FILTER_SORT_SLOTS}"
)


def tile(pool: str, index: int, vote_var: str, name_var: str, indent: str) -> str:
    if pool == "voted":
        slot_id = f"mv-voted-slot-{index}"
        tile_id = f"mv-voted-{index}"
        shot_id = f"mv-voted-shot-{index}"
        fav_id = f"mv-voted-fav-{index}"
    else:
        slot_id = f"mv-slot-{index}"
        tile_id = f"mv-{index}"
        shot_id = f"mv-shot-{index}"
        fav_id = f"mv-fav-{index}"
    return "\n".join(
        [
            f'{indent}<Panel id="{slot_id}" class="MapSlot is-off" hittest="false">',
            f'{indent}\t<Button id="{tile_id}" class="MapTile">',
            f'{indent}\t\t<Panel id="{shot_id}" class="MapShot mv-map-default" hittest="false" />',
            f'{indent}\t\t<Panel class="MapFade" hittest="false" />',
            f'{indent}\t\t<Label class="MapName stratum-bold-condensed" text="{{s:{name_var}}}" hittest="false" />',
            f'{indent}\t\t<Label class="MapVotes stratum-bold" text="{{s:{vote_var}}}" hittest="false" />',
            f'{indent}\t\t<Panel class="MapWinnerCheck" hittest="false" />',
            f"{indent}\t</Button>",
            f'{indent}\t<Button id="{fav_id}" class="FavBtn">',
            f'{indent}\t\t<Panel class="FavIcon" hittest="false" />',
            f"{indent}\t</Button>",
            f"{indent}</Panel>",
        ]
    )


def chip(kind: str, index: int, var: str, indent: str) -> str:
    chip_id = f"mv-{kind}-{index}"
    return "\n".join(
        [
            f'{indent}<Button id="{chip_id}" class="FilterChip is-off">',
            f'{indent}\t<Label class="FilterChipLabel stratum-bold-condensed" text="{{s:{var}}}" hittest="false" />',
            f"{indent}</Button>",
        ]
    )


def rewrite_hud_ladders() -> None:
    """Keep vw-* / rows-* ladders in the versioned hud VCSS aligned with SLOT_COUNT / ROW_COUNT."""
    if not HUD_VCSS.is_file():
        return
    text = HUD_VCSS.read_text(encoding="utf-8")
    vw_lines = ["/* BEGIN vw-ladder */"]
    for i in range(SLOT_COUNT + 1):
        vw_lines.append(f".VotedStrip.vw-{i} {{ width: {i * VOTED_SLOT_PITCH_PX}px; }}")
    vw_lines.append("/* END vw-ladder */")
    rows_lines = ["/* BEGIN rows-ladder */"]
    for i in range(ROW_COUNT + 1):
        rows_lines.append(f".MapCatalog.rows-{i} {{ height: {i * CATALOG_ROW_HEIGHT_PX}px; }}")
    rows_lines.append("/* END rows-ladder */")

    if "/* BEGIN vw-ladder */" in text:
        text = re.sub(
            re.escape("/* BEGIN vw-ladder */") + r".*?" + re.escape("/* END vw-ladder */"),
            "\n".join(vw_lines),
            text,
            flags=re.S,
        )
    else:
        # Replace the first hand-written ladder block once.
        text = re.sub(
            r"/\* Slot pitch = 110px tile \+ 8px \+ 8px margin = 126px \*/\n(?:\.VotedStrip\.vw-\d+ \{ width: \d+px; \}\n)+",
            "/* Slot pitch = 110px tile + 8px + 8px margin = 126px */\n" + "\n".join(vw_lines) + "\n",
            text,
            count=1,
        )

    if "/* BEGIN rows-ladder */" in text:
        text = re.sub(
            re.escape("/* BEGIN rows-ladder */") + r".*?" + re.escape("/* END rows-ladder */"),
            "\n".join(rows_lines),
            text,
            flags=re.S,
        )
    else:
        text = re.sub(
            r"(?:\.MapCatalog\.rows-\d+ \{ height: \d+px; \}\n)+",
            "\n".join(rows_lines) + "\n",
            text,
            count=1,
        )

    HUD_VCSS.write_text(text, encoding="utf-8")


def build() -> str:
    lines: list[str] = [
        "<!-- AUTO-GENERATED by tools/generate_vote_xml.py — do not edit by hand.",
        f"     MapVote:mapvote {LAYOUT_TAG} -->",
        "<root>",
        "\t<styles>",
        '\t\t<include src="s2r://panorama/styles/csgostyles.vcss" />',
        f'\t\t<include src="s2r://panorama/styles/custom_game/mapvote/{HUD_VCSS_NAME}" />',
        "\t</styles>",
        "",
        f"\t<!-- MapVote:mapvote {LAYOUT_TAG} -->",
        '\t<Panel class="HudScreen" hittest="false">',
        '\t\t<Panel id="Vote" class="VoteRoot is-off" hittest="false">',
		'\t\t\t<Panel class="mv-glass" hittest="false" />',
		'\t\t\t<Panel class="mv-scrim" hittest="false" />',
        '\t\t\t<Panel class="VoteColumn" hittest="false">',
        '\t\t\t\t<Panel class="VoteTopBar" hittest="false">',
        '\t\t\t\t\t<Label class="VoteTitle stratum-bold-condensed" text="{s:mv_title}" hittest="false" />',
        '\t\t\t\t\t<Button id="mv-minimize" class="MinimizeBtn">',
        '\t\t\t\t\t\t<Label class="MinimizeLabel stratum-bold-condensed" text="{s:mv_chip}" hittest="false" />',
        "\t\t\t\t\t</Button>",
        "\t\t\t\t</Panel>",
        '\t\t\t\t<Panel class="VoteBody" hittest="false">',
        '\t\t\t\t\t<Panel id="mv-voted-section" class="VotedSection" hittest="false">',
        '\t\t\t\t\t\t<Panel class="VotedRow" hittest="false">',
        '\t\t\t\t\t\t\t<Label id="mv-voted-hint" class="VotedHint stratum-bold-condensed" text="{s:mv_hint}" hittest="false" />',
        '\t\t\t\t\t\t\t<Panel id="mv-voted-strip" class="VotedStrip vw-0" hittest="false">',
    ]

    for i in range(SLOT_COUNT):
        lines.append(tile("voted", i, f"vv{i}", f"vn{i}", "\t\t\t\t\t\t\t\t"))

    lines.extend(
        [
            "\t\t\t\t\t\t\t</Panel>",
            "\t\t\t\t\t\t</Panel>",
            "\t\t\t\t\t</Panel>",
            '\t\t\t\t\t<Panel id="mv-filters" class="FilterBar is-off" hittest="false">',
            '\t\t\t\t\t\t<Panel class="FilterTypeRow" hittest="false">',
        ]
    )

    for i in range(FILTER_TYPE_SLOTS):
        lines.append(chip("ft", i, f"ft{i}", "\t\t\t\t\t\t\t"))

    lines.extend(
        [
            "\t\t\t\t\t\t</Panel>",
            '\t\t\t\t\t\t<Panel class="FilterSortRow" hittest="false">',
        ]
    )

    for i in range(FILTER_SORT_SLOTS):
        lines.append(chip("fs", i, f"fs{i}", "\t\t\t\t\t\t\t"))

    lines.extend(
        [
            "\t\t\t\t\t\t</Panel>",
            "\t\t\t\t\t</Panel>",
            '\t\t\t\t\t<Panel class="MapGridHost" hittest="false">',
            '\t\t\t\t\t\t<Panel class="MapGrid" hittest="false">',
            '\t\t\t\t\t\t\t<Label id="mv-empty" class="MapEmpty stratum-bold-condensed is-off" text="{s:mv_empty}" hittest="false" />',
            '\t\t\t\t\t\t\t<Panel id="mv-catalog" class="MapCatalog rows-0" hittest="false">',
        ]
    )

    for row in range(ROW_COUNT):
        lines.append(
            f'\t\t\t\t\t\t\t\t<Panel id="mv-crow-{row}" class="CatalogRow is-off" hittest="false">'
        )
        start = row * COLS
        end = min(start + COLS, SLOT_COUNT)
        for i in range(start, end):
            lines.append(tile("grid", i, f"v{i}", f"n{i}", "\t\t\t\t\t\t\t\t\t"))
        lines.append("\t\t\t\t\t\t\t\t</Panel>")

    lines.extend(
        [
            "\t\t\t\t\t\t\t</Panel>",
            "\t\t\t\t\t\t</Panel>",
            "\t\t\t\t\t</Panel>",
            "\t\t\t\t</Panel>",
            '\t\t\t\t<Panel class="CreditBar" hittest="false">',
            f'\t\t\t\t\t<Label class="CreditLabel stratum-bold-condensed" text="{CREDIT}" hittest="false" />',
            "\t\t\t\t</Panel>",
            "\t\t\t</Panel>",
            "\t\t</Panel>",
            "\t</Panel>",
            "</root>",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help=f"exit 1 if committed {VOTE_XML_NAME} differs from generated output",
    )
    args = parser.parse_args()
    text = build().replace("\r\n", "\n")
    if args.check:
        if not OUT.is_file():
            print(f"missing {OUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        existing = OUT.read_text(encoding="utf-8").replace("\r\n", "\n")
        if existing != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run tools/generate_vote_xml.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    rewrite_hud_ladders()
    print(f"wrote {OUT.relative_to(ROOT)} ({LAYOUT_TAG})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
