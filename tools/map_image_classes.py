#!/usr/bin/env python3
"""Generate src/MapVote/Maps/MapImageClasses.Stems.cs from stock_maps.txt + workshop PNGs."""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STOCK_LIST = ROOT / "tools" / "stock_maps.txt"
IMAGES = ROOT / "workshop" / "content" / "panorama" / "images" / "custom_game" / "mapvote" / "maps"
OUT = ROOT / "src" / "MapVote" / "Maps" / "MapImageClasses.Stems.cs"
MAP_RE = re.compile(r"^[a-z0-9][a-z0-9_]{0,48}$")


def load_stock_stems() -> list[str]:
    if not STOCK_LIST.is_file():
        return []
    stems: list[str] = []
    for line in STOCK_LIST.read_text(encoding="utf-8").splitlines():
        name = line.split("#", 1)[0].strip().lower()
        if name and MAP_RE.match(name):
            stems.append(name)
    return sorted(dict.fromkeys(stems))


def load_workshop_stems() -> list[str]:
    stems: list[str] = []
    if not IMAGES.is_dir():
        return stems
    for png in sorted(IMAGES.glob("*.png")):
        stem = png.stem.lower()
        if stem == "default" or not MAP_RE.match(stem):
            continue
        if (IMAGES / f"{stem}.vtex").is_file():
            stems.append(stem)
    return stems


def csharp_set(name: str, stems: list[str]) -> str:
    if not stems:
        return f"        private static readonly HashSet<string> {name} = new(StringComparer.Ordinal);"
    items = ",\n".join(f'            "{s}"' for s in stems)
    return (
        f"        private static readonly HashSet<string> {name} =\n"
        f"            new(StringComparer.Ordinal)\n"
        f"            {{\n{items},\n"
        f"            }};"
    )


def write_stems_cs(stock: list[str] | None = None, workshop: list[str] | None = None) -> Path:
    stock_stems = stock if stock is not None else load_stock_stems()
    workshop_stems = workshop if workshop is not None else load_workshop_stems()
    text = "\n".join(
        [
            "// <auto-generated> by tools/map_image_classes.py — do not edit.",
            "namespace MapVote.Maps",
            "{",
            "    public static partial class MapImageClasses",
            "    {",
            csharp_set("StockStems", stock_stems),
            "",
            csharp_set("WorkshopStems", workshop_stems),
            "    }",
            "}",
            "",
        ]
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    return OUT


if __name__ == "__main__":
    path = write_stems_cs()
    print(f"wrote {path.relative_to(ROOT)}")
