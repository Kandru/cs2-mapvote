#!/usr/bin/env python3
"""Rewrite the /* BEGIN mv-map-stock */ block in hud.vcss from tools/stock_maps.txt."""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from map_image_classes import write_stems_cs
from mapvote_layout import HUD_VCSS_NAME

ROOT = Path(__file__).resolve().parents[1]
STOCK_LIST = ROOT / "tools" / "stock_maps.txt"
HUD_VCSS = ROOT / "workshop" / "content" / "panorama" / "styles" / "custom_game" / "mapvote" / HUD_VCSS_NAME
CSS_BEGIN = "/* BEGIN mv-map-stock */"
CSS_END = "/* END mv-map-stock */"
MAP_RE = re.compile(r"^[a-z0-9][a-z0-9_]{0,48}$")
STOCK_CLASS_PREFIX = "mv-map-stock-"


def load_stems(path: Path = STOCK_LIST) -> list[str]:
    stems: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        name = line.split("#", 1)[0].strip().lower()
        if not name:
            continue
        if not MAP_RE.match(name):
            raise SystemExit(f"invalid stock map name: {name!r}")
        stems.append(name)
    return sorted(dict.fromkeys(stems))


def write_stock_list(stems: list[str], path: Path = STOCK_LIST) -> None:
    cleaned = sorted({s.lower() for s in stems if MAP_RE.match(s.lower())})
    lines = [
        "# Official CS2 maps that ship a 360p screenshot under",
        "# panorama/images/map_icons/screenshots/360p/{map}_png.vtex",
        "# Regenerated by: make images GAME_DIR=/path/to/game/csgo",
        "# CSS classes: .mv-map-stock-{map} (workshop palette keeps .mv-map-{map})",
        "",
    ]
    lines.extend(cleaned)
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def stock_url(stem: str) -> str:
    """In-game HUD path (must match validate_panorama STOCK_URL_RE)."""
    return f's2r://panorama/images/map_icons/screenshots/360p/{stem}_png.vtex'


def render_block(stems: list[str]) -> str:
    lines = [CSS_BEGIN, ""]
    for stem in stems:
        lines.append(f".{STOCK_CLASS_PREFIX}{stem}")
        lines.append("{")
        lines.append(f'\tbackground-image: url("{stock_url(stem)}");')
        lines.append("\tbackground-size: 100% 100%;")
        lines.append("\tbackground-position: center center;")
        lines.append("\tbackground-repeat: no-repeat;")
        lines.append("}")
        lines.append("")
    lines.append(CSS_END)
    return "\n".join(lines)


def rewrite_hud_stock_css(stems: list[str] | None = None) -> int:
    if not HUD_VCSS.is_file():
        raise SystemExit(f"missing {HUD_VCSS}")
    if stems is None:
        if not STOCK_LIST.is_file():
            raise SystemExit(f"missing {STOCK_LIST}")
        stems = load_stems()

    block = render_block(stems)
    text = HUD_VCSS.read_text(encoding="utf-8")

    if CSS_BEGIN in text and CSS_END in text:
        pattern = re.compile(re.escape(CSS_BEGIN) + r".*?" + re.escape(CSS_END), re.S)
        text = pattern.sub(block, text)
    else:
        palette = "/* BEGIN mv-map-palette */"
        if palette not in text:
            raise SystemExit("hud.vcss missing mv-map-palette markers")
        text = text.replace(palette, block + "\n\n" + palette)

    HUD_VCSS.write_text(text, encoding="utf-8")
    write_stems_cs(stock=stems)
    return len(stems)


def main() -> int:
    count = rewrite_hud_stock_css()
    print(f"[stock] wrote {count} stock map classes ({STOCK_CLASS_PREFIX}*)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
