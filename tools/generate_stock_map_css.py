#!/usr/bin/env python3
"""Rewrite the /* BEGIN mv-map-stock */ block in hud.vcss from tools/stock_maps.txt."""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from mapvote_layout import HUD_VCSS_NAME

ROOT = Path(__file__).resolve().parents[1]
STOCK_LIST = ROOT / "tools" / "stock_maps.txt"
HUD_VCSS = ROOT / "workshop" / "content" / "panorama" / "styles" / "custom_game" / "mapvote" / HUD_VCSS_NAME
CSS_BEGIN = "/* BEGIN mv-map-stock */"
CSS_END = "/* END mv-map-stock */"
MAP_RE = re.compile(r"^[a-z0-9][a-z0-9_]{0,48}$")
PALETTE_BEGIN = "/* BEGIN mv-map-palette */"


def ignored_stock_map(name: str) -> bool:
    """Official shots we do not ship: the random tile and lobby backgrounds."""
    return name == "random" or name.startswith("lobby_")


def load_stems(path: Path = STOCK_LIST) -> list[str]:
    stems: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        name = line.split("#", 1)[0].strip().lower()
        if not name or ignored_stock_map(name):
            continue
        if not MAP_RE.match(name):
            raise SystemExit(f"invalid stock map name: {name!r}")
        stems.append(name)
    return sorted(dict.fromkeys(stems))


def write_stock_list(stems: list[str], path: Path = STOCK_LIST) -> None:
    cleaned = sorted(
        {s.lower() for s in stems if MAP_RE.match(s.lower()) and not ignored_stock_map(s.lower())}
    )
    lines = [
        "# Official CS2 maps extracted into panorama/images/.../maps/map_{name}.png",
        "# Source shots: panorama/images/map_icons/screenshots/{1080,720,360}p/",
        "# Skips random and lobby_*. Regenerated by: make images GAME_DIR=/path/to/game/csgo",
        "# CSS classes: .mv-map-map_{name} (workshop palette uses .mv-map-ws_{name})",
        "",
    ]
    lines.extend(cleaned)
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def map_image_url(stem: str) -> str:
    """Addon image path (must match validate_panorama). stem is the file name, e.g. map_de_dust2."""
    return f"s2r://panorama/images/custom_game/mapvote/maps/{stem}.vtex"


def render_map_block(begin: str, end: str, stems: list[str]) -> str:
    lines = [begin, ""]
    for stem in stems:
        lines.append(f".mv-map-{stem}")
        lines.append("{")
        lines.append(f'\tbackground-image: url("{map_image_url(stem)}");')
        lines.append("}")
        lines.append("")
    lines.append(end)
    return "\n".join(lines)


def write_map_block(begin: str, end: str, stems: list[str], *, insert_before: str | None = None) -> None:
    if not HUD_VCSS.is_file():
        raise SystemExit(f"missing {HUD_VCSS}")
    block = render_map_block(begin, end, stems)
    text = HUD_VCSS.read_text(encoding="utf-8")
    if begin in text and end in text:
        pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
        text = pattern.sub(block, text)
    elif insert_before and insert_before in text:
        text = text.replace(insert_before, block + "\n\n" + insert_before, 1)
    else:
        raise SystemExit(f"{HUD_VCSS_NAME} missing {begin} … {end}")
    HUD_VCSS.write_text(text, encoding="utf-8")


def rewrite_hud_stock_css(stems: list[str] | None = None) -> int:
    if stems is None:
        if not STOCK_LIST.is_file():
            raise SystemExit(f"missing {STOCK_LIST}")
        stems = load_stems()
    write_map_block(CSS_BEGIN, CSS_END, [f"map_{stem}" for stem in stems], insert_before=PALETTE_BEGIN)
    return len(stems)


def main() -> int:
    count = rewrite_hud_stock_css()
    print(f"[stock] wrote {count} stock map classes (.mv-map-map_*)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
