#!/usr/bin/env python3
"""Append stock map classes to the /* BEGIN mv-map-stock */ block in maps.vcss.

Existing classes are never removed here: the list can lag behind the CSS while
images are being prepared. Use ``prune_maps_stock_css`` explicitly to remove
classes that are no longer listed.
"""
from __future__ import annotations

import re
import sys
from collections.abc import Iterable
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from map_names import is_playable_map_id, ignored_stock_map, normalize_map_id
from mapvote_layout import MAPS_VCSS_NAME

ROOT = Path(__file__).resolve().parents[1]
STOCK_LIST = ROOT / "tools" / "stock_maps.txt"
MAPS_VCSS = ROOT / "workshop" / "content" / "panorama" / "styles" / "custom_game" / "mapvote" / MAPS_VCSS_NAME
CSS_BEGIN = "/* BEGIN mv-map-stock */"
CSS_END = "/* END mv-map-stock */"
PALETTE_BEGIN = "/* BEGIN mv-map-palette */"

MAP_CLASS_RE = re.compile(r"^\.mv-map-([a-z0-9_]+)\s*\{", re.M)


def clean_stock_stems(stems: Iterable[str]) -> list[str]:
    names = {normalize_map_id(stem) for stem in stems}
    return sorted(
        name
        for name in names
        if name and is_playable_map_id(name) and not ignored_stock_map(name)
    )


def load_stems(path: Path = STOCK_LIST) -> list[str]:
    stems: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        name = normalize_map_id(line.split("#", 1)[0])
        if not name:
            continue
        if ignored_stock_map(name):
            continue
        if not is_playable_map_id(name):
            print(f"[stock] skipping non-playable stock map {name!r}", file=sys.stderr)
            continue
        stems.append(name)
    return clean_stock_stems(stems)


def write_stock_list(stems: Iterable[str], path: Path = STOCK_LIST) -> None:
    lines = [
        "# Official CS2 maps extracted into panorama/images/.../maps/map_{name}.png",
        "# Source shots: panorama/images/map_icons/screenshots/{1080,720,360}p/",
        "# Skips random and lobby_*. Regenerated by: make images GAME_DIR=/path/to/game/csgo",
        "# CSS classes live in maps_v1.vcss: .mv-map-map_{name} (workshop uses .mv-map-ws_{name})",
        "",
        *clean_stock_stems(stems),
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def map_image_url(stem: str) -> str:
    """Addon image path (must match validate_panorama). stem is the file name, e.g. map_de_dust2."""
    return f"s2r://panorama/images/custom_game/mapvote/maps/{stem}.vtex"


def render_map_entries(stems: Iterable[str]) -> str:
    return "\n\n".join(
        f'.mv-map-{stem}\n{{\n\tbackground-image: url("{map_image_url(stem)}");\n}}'
        for stem in stems
    )


def render_map_block(begin: str, end: str, stems: Iterable[str]) -> str:
    entries = render_map_entries(stems)
    return f"{begin}\n\n{entries}\n\n{end}" if entries else f"{begin}\n\n{end}"


def find_map_block(text: str, begin: str, end: str) -> re.Match[str] | None:
    return re.search(re.escape(begin) + r".*?" + re.escape(end), text, re.S)


def block_stems(block: str) -> list[str]:
    return list(dict.fromkeys(MAP_CLASS_RE.findall(block)))


def read_maps_css() -> str:
    if not MAPS_VCSS.is_file():
        raise SystemExit(f"missing {MAPS_VCSS}")
    return MAPS_VCSS.read_text(encoding="utf-8")


def write_maps_css(text: str) -> None:
    MAPS_VCSS.write_text(text, encoding="utf-8")


def merge_map_block(
    begin: str,
    end: str,
    stems: Iterable[str],
    *,
    insert_before: str | None = None,
) -> int:
    """Append classes missing from the block; never remove existing classes."""
    text = read_maps_css()
    unique = list(dict.fromkeys(stems))
    match = find_map_block(text, begin, end)
    if match is not None:
        existing = set(block_stems(match.group(0)))
        missing = [stem for stem in unique if stem not in existing]
        if not missing:
            return 0
        block = match.group(0).replace(
            end,
            f"{render_map_entries(missing)}\n\n{end}",
            1,
        )
        write_maps_css(text[: match.start()] + block + text[match.end() :])
        return len(missing)

    if insert_before and insert_before in text:
        block = render_map_block(begin, end, unique)
        write_maps_css(text.replace(insert_before, f"{block}\n\n{insert_before}", 1))
        return len(unique)

    raise SystemExit(f"{MAPS_VCSS_NAME} missing {begin} … {end}")


def prune_map_block(begin: str, end: str, keep_stems: Iterable[str]) -> int:
    """Remove block entries whose stem is not in ``keep_stems``."""
    text = read_maps_css()
    match = find_map_block(text, begin, end)
    if match is None:
        raise SystemExit(f"{MAPS_VCSS_NAME} missing {begin} … {end}")

    keep = set(keep_stems)
    existing = block_stems(match.group(0))
    kept = [stem for stem in existing if stem in keep]
    removed = len(existing) - len(kept)
    if removed == 0:
        return 0

    block = render_map_block(begin, end, kept)
    write_maps_css(text[: match.start()] + block + text[match.end() :])
    return removed


def merge_maps_stock_css(stems: Iterable[str] | None = None) -> int:
    """Append stock classes from ``stock_maps.txt`` (or ``stems``)."""
    if stems is None:
        if not STOCK_LIST.is_file():
            raise SystemExit(f"missing {STOCK_LIST}")
        stems = load_stems()
    cleaned = clean_stock_stems(stems)
    return merge_map_block(
        CSS_BEGIN,
        CSS_END,
        [f"map_{stem}" for stem in cleaned],
        insert_before=PALETTE_BEGIN,
    )


def prune_maps_stock_css(keep_stems: Iterable[str] | None = None) -> int:
    """Remove stock classes not present in ``stock_maps.txt`` (or ``keep_stems``)."""
    if keep_stems is None:
        if not STOCK_LIST.is_file():
            print(f"[stock] missing {STOCK_LIST}; skipping prune", file=sys.stderr)
            return 0
        keep_stems = load_stems()

    keep = {f"map_{stem}" for stem in clean_stock_stems(keep_stems)}
    if not keep:
        print("[stock] empty stock list; skipping prune", file=sys.stderr)
        return 0
    return prune_map_block(CSS_BEGIN, CSS_END, keep)


def main() -> int:
    added = merge_maps_stock_css()
    print(
        f"[stock] appended {added} stock map classes "
        f"(.mv-map-map_*) → {MAPS_VCSS.relative_to(ROOT)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
